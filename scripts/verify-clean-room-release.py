def compare_archive_pair(left: Path, right: Path) -> tuple[list[str], dict]:
    failures: list[str] = []
    left = Path(left)
    right = Path(right)
    left_sidecar = Path(str(left) + ".sha256")
    right_sidecar = Path(str(right) + ".sha256")
    for path in (left, right, left_sidecar, right_sidecar):
        if not path.is_file():
            failures.append(f"reproducibility artifact is missing: {path}")
    if failures:
        return failures, {}
    left_digest = sha256(left)
    right_digest = sha256(right)
    byte_identical = left.stat().st_size == right.stat().st_size and left_digest == right_digest
    sidecar_identical = sidecar_binds(left_sidecar, left, left_digest) and sidecar_binds(
        right_sidecar, right, right_digest
    )
    try:
        left_manifest = embedded_manifest(left)
        right_manifest = embedded_manifest(right)
        manifest_identical = left_manifest == right_manifest
    except (OSError, KeyError, ValueError, zipfile.BadZipFile) as error:
        left_manifest = {}
        right_manifest = {}
        manifest_identical = False
        failures.append(f"clean-room embedded manifest could not be verified: {error}")
    if not byte_identical:
        failures.append("clean-room archives are not byte-identical")
    if not sidecar_identical:
        failures.append("one or both clean-room checksum sidecars do not bind to their archive")
    if not manifest_identical:
        failures.append("clean-room embedded manifests are not identical")
    return failures, {
        "left": {"bytes": left.stat().st_size, "sha256": left_digest},
        "right": {"bytes": right.stat().st_size, "sha256": right_digest},
        "byte_identical": byte_identical,
        "sidecar_identical": sidecar_identical,
        "manifest_identical": manifest_identical,
        "left_manifest": left_manifest,
        "right_manifest": right_manifest,
    }


def materialize_and_run(
    source_root: Path,
    destination: Path,
    label: str,
    release_id: str,
    generated_at: str,
) -> tuple[Path, dict]:
    """Run the one canonical clean-room pipeline; no caller command is accepted."""
    clean_root = destination / label
    copy_clean_source(source_root, clean_root)
    snapshot = source_tree_evidence(clean_root)
    helpers = helper_evidence(clean_root)
    pinned_python_dependencies = pinned_audit_requirements_evidence(
        clean_root / "SITE_PACKAGE"
    )
    output = clean_root / "ss-site-clean-room.zip"
    environment, environment_evidence = clean_environment(
        destination / f"{label}-external-inputs", generated_at
    )
    run_with_lock = clean_root / "SITE_PACKAGE/scripts/run-with-build-lock.py"
    build_helper = clean_root / "SITE_PACKAGE/scripts/build-clean-room-release.py"
    command = [
        sys.executable,
        str(run_with_lock),
        "--delivery-root",
        str(clean_root),
        "--",
        sys.executable,
        str(build_helper),
        str(output),
        "--release-id",
        release_id,
        "--generated-at",
        generated_at,
    ]
    subprocess.run(command, cwd=clean_root / "SITE_PACKAGE", env=environment, check=True)
    installed_inventory = installed_distribution_inventory(
        Path(environment["TMPDIR"]) / "seminar-schools-python-audit-deps"
    )
    if installed_inventory != pinned_python_dependencies["locked_distributions"]:
        raise ValueError(
            "installed clean-room Python audit inventory differs from its resolved lock"
        )
    pinned_python_dependencies.update(
        {
            "installed_distribution_count": len(installed_inventory),
            "installed_distributions": installed_inventory,
            "installed_inventory_matches_lock": True,
        }
    )
    return output, {
        "source_snapshot": snapshot,
        "pipeline_helpers": helpers,
        "pipeline_steps": canonical_pipeline_steps(release_id, generated_at),
        "pinned_python_audit_dependencies": pinned_python_dependencies,
        "pinned_python_audit_dependencies_verified": True,
        "external_inputs": environment_evidence,
    }


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--compare", nargs=2, type=Path, metavar=("LEFT_ZIP", "RIGHT_ZIP"))
    parser.add_argument("--reference-archive", type=Path)
    parser.add_argument("--source-root", type=Path, default=DELIVERY_ROOT)
    parser.add_argument("--delivery-root", type=Path, default=DELIVERY_ROOT)
    parser.add_argument(
        "--command-json",
        help="retired and forbidden; the canonical reference pipeline is verifier-owned",
    )
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument(
        "--pipeline-id",
        help="retired and forbidden; mode-specific pipeline identity is verifier-owned",
    )
    args = parser.parse_args(argv)
    if args.command_json is not None:
        parser.error("--command-json is forbidden; the verifier constructs the fixed pipeline")
    if args.pipeline_id is not None:
        parser.error("--pipeline-id is verifier-owned and cannot be supplied by a caller")
    if args.compare and args.reference_archive:
        parser.error("use either --compare or --reference-archive, not both")
    if not args.compare and not args.reference_archive:
        parser.error("use --compare or --reference-archive")
    require_release_build_lock(args.delivery_root)

    if args.compare:
        left, right = args.compare
        failures, evidence = compare_archive_pair(left, right)
        mode_evidence = {
            "mode": "compare_only",
            "canonical_pipeline": False,
            "pipeline_id": COMPARE_PIPELINE_ID,
            "pipeline_steps": [
                {
                    "order": 1,
                    "action": "compare_caller_supplied_archives",
                    "canonical_rebuild_executed": False,
                }
            ],
        }
    else:
        reference = args.reference_archive.resolve()
        try:
            release_id, generated_at = release_metadata(reference)
        except (OSError, KeyError, ValueError, zipfile.BadZipFile) as error:
            parser.error(str(error))
        with tempfile.TemporaryDirectory(prefix="ss-clean-room-release-") as temporary:
            root = Path(temporary)
            left = reference
            right, rebuild_evidence = materialize_and_run(
                args.source_root.resolve(),
                root,
                "clean-rebuild",
                release_id,
                generated_at,
            )
            failures, evidence = compare_archive_pair(left, right)
            archive_inputs = archive_rebuild_input_evidence(right)
            snapshot_matches_archive = rebuild_evidence["source_snapshot"] == archive_inputs
            if not snapshot_matches_archive:
                failures.append(
                    "clean-room prebuild snapshot differs from the final archive rebuild inputs"
                )
        mode_evidence = {
            "mode": "reference_rebuild",
            "canonical_pipeline": True,
            "pipeline_id": PIPELINE_ID,
            "release_id": release_id,
            "generated_at": generated_at,
            "source_snapshot_matches_archive": snapshot_matches_archive,
            "archive_rebuild_inputs": archive_inputs,
            **rebuild_evidence,
        }

    check_fields = ["byte_identical", "sidecar_identical", "manifest_identical"]
    if not args.compare:
        check_fields.append("source_snapshot_matches_archive")
        check_fields.append("pinned_python_audit_dependencies_verified")
    result_flags = {**evidence, **mode_evidence}
    report = {
        "schema": REPORT_SCHEMA,
        "status": "failed" if failures else "passed",
        "total_checks": len(check_fields),
        "passed_checks": sum(
            int(result_flags.get(field) is True)
            for field in check_fields
        ),
        "failed_checks": failures,
        **mode_evidence,
        **evidence,
    }
    write_json_atomic(args.report, report)
    if failures:
        print("CLEAN-ROOM REPRODUCIBILITY FAILED")
        for failure in failures:
            print(f" - {failure}")
        raise SystemExit(1)
    print(f"CLEAN-ROOM REPRODUCIBILITY PASSED — both archives are {evidence['left']['sha256']}.")


if __name__ == "__main__":
    main()
