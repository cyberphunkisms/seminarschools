def sidecar_binds(sidecar: Path, archive: Path, digest: str) -> bool:
    try:
        text = sidecar.read_text(encoding="utf-8")
    except OSError:
        return False
    match = re.fullmatch(r"([a-f0-9]{64})  ([^\r\n]+)\r?\n?", text)
    return bool(match and match.group(1) == digest and match.group(2) == archive.name)


def embedded_manifest(path: Path) -> dict:
    with zipfile.ZipFile(path, "r") as archive:
        payload = archive.read("PACKAGE_CONTENTS_SHA256.json")
    value = json.loads(payload)
    return {
        "sha256": hashlib.sha256(payload).hexdigest(),
        "schema": value.get("schema"),
        "package_kind": value.get("package_kind"),
        "release_id": value.get("release_id"),
        "generated_at": value.get("generated_at"),
        "file_count": value.get("file_count"),
    }


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(CHUNK), b""):
            digest.update(chunk)
    return digest.hexdigest()


def sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def release_metadata(reference_archive: Path) -> tuple[str, str]:
    manifest = embedded_manifest(reference_archive)
    release_id = manifest.get("release_id")
    generated_at = manifest.get("generated_at")
    if not isinstance(release_id, str) or not release_id.strip():
        raise ValueError("reference archive embedded manifest lacks a release_id")
    if not isinstance(generated_at, str) or not generated_at.strip():
        raise ValueError("reference archive embedded manifest lacks generated_at")
    try:
        stamp = datetime.fromisoformat(generated_at.replace("Z", "+00:00"))
    except ValueError as error:
        raise ValueError("reference archive generated_at is not ISO-8601") from error
    if stamp.tzinfo is None:
        raise ValueError("reference archive generated_at must include a timezone")
    return release_id, generated_at


def generated_at_epoch(generated_at: str) -> str:
    stamp = datetime.fromisoformat(generated_at.replace("Z", "+00:00"))
    if stamp.tzinfo is None:
        raise ValueError("generated_at must include a timezone")
    return str(int(stamp.timestamp()))


def source_tree_evidence(root: Path) -> dict:
    """Hash the canonical rebuild inputs before any build runs.

    The two package manifests are regenerated by packaging and are therefore
    excluded from both this digest and the independently derived ZIP digest.
    """
    rows: list[tuple[str, int, str]] = []
    total_bytes = 0
    for current, directory_names, file_names in os.walk(root, topdown=True, followlinks=False):
        current_path = Path(current)
        symlinked_directories = [
            name for name in directory_names if (current_path / name).is_symlink()
        ]
        if symlinked_directories:
            raise ValueError(
                "clean source snapshot contains directory symlinks: "
                + ", ".join(sorted(symlinked_directories))
            )
        directory_names[:] = sorted(directory_names)
        for name in sorted(file_names):
            candidate = current_path / name
            if candidate.is_symlink() or not candidate.is_file():
                raise ValueError(f"clean source snapshot contains a non-regular file: {candidate}")
            relative = candidate.relative_to(root).as_posix()
            if relative in GENERATED_MANIFEST_PATHS:
                continue
            size = candidate.stat().st_size
            rows.append((relative, size, sha256(candidate)))
            total_bytes += size
    digest = hashlib.sha256()
    # os.walk() is depth-first, while package manifests are globally sorted by
    # archive path. Canonicalize both evidence streams to the same ordering so
    # identical trees cannot fail merely because nested paths were visited at
    # different times.
    for relative, size, file_digest in sorted(rows, key=lambda value: value[0]):
        digest.update(f"{relative}\0{size}\0{file_digest}\n".encode("utf-8"))
    return {
        "tree_sha256": digest.hexdigest(),
        "file_count": len(rows),
        "total_bytes": total_bytes,
        "excluded_generated_manifests": sorted(GENERATED_MANIFEST_PATHS),
    }


def archive_rebuild_input_evidence(path: Path) -> dict:
    """Derive the same prebuild-input digest independently from a final ZIP."""
    with zipfile.ZipFile(path, "r") as archive:
        manifest = json.loads(archive.read("PACKAGE_CONTENTS_SHA256.json"))
    rows = [
        row for row in (manifest.get("files") or [])
        if row.get("path") not in GENERATED_MANIFEST_PATHS
    ]
    digest = hashlib.sha256()
    total_bytes = 0
    for row in sorted(rows, key=lambda value: str(value.get("path") or "")):
        relative = str(row.get("path") or "")
        size = row.get("bytes")
        file_digest = str(row.get("sha256") or "")
        if type(size) is not int or size < 0 or not re.fullmatch(r"[a-f0-9]{64}", file_digest):
            raise ValueError(f"final archive has malformed rebuild-input evidence: {relative}")
        digest.update(f"{relative}\0{size}\0{file_digest}\n".encode("utf-8"))
        total_bytes += size
    return {
        "tree_sha256": digest.hexdigest(),
        "file_count": len(rows),
        "total_bytes": total_bytes,
        "excluded_generated_manifests": sorted(GENERATED_MANIFEST_PATHS),
    }


def helper_evidence(clean_root: Path) -> list[dict]:
    rows: list[dict] = []
    for relative in PIPELINE_HELPERS:
        helper = clean_root / relative
        trusted_helper = DELIVERY_ROOT / relative
        if not helper.is_file() or helper.is_symlink():
            raise ValueError(f"canonical clean-room helper is missing: {relative}")
        if not trusted_helper.is_file() or trusted_helper.is_symlink():
            raise ValueError(f"trusted canonical helper is missing: {relative}")
        actual_digest = sha256(helper)
        trusted_digest = sha256(trusted_helper)
        if actual_digest != trusted_digest:
            raise ValueError(f"clean source snapshot substituted canonical helper: {relative}")
        rows.append(
            {
                "path": relative,
                "bytes": helper.stat().st_size,
                "sha256": actual_digest,
                "trusted_sha256": trusted_digest,
                "matches_trusted_helper": True,
            }
        )
    return rows


def executable_input_evidence(environment: dict[str, str]) -> list[dict]:
    """Hash executable files that can materially affect the clean rebuild."""
    candidates = {
        "python": sys.executable,
        "node": shutil.which("node", path=environment.get("PATH")),
        "npm": shutil.which("npm.cmd" if os.name == "nt" else "npm", path=environment.get("PATH")),
        **{
            key: environment.get(key)
            for key in (
                "CHROME_EXECUTABLE",
                "CHROME_PATH",
                "CHROMIUM_PATH",
                "PUPPETEER_EXECUTABLE_PATH",
            )
            if environment.get(key)
        },
    }
    missing_mandatory = [name for name in ("python", "node", "npm") if not candidates.get(name)]
    if missing_mandatory:
        raise ValueError(
            "clean-room environment cannot resolve mandatory executables: "
            + ", ".join(missing_mandatory)
        )
    rows: list[dict] = []
    for name, configured_path in sorted(candidates.items()):
        if not configured_path:
            continue
        candidate = Path(configured_path).expanduser()
        row = {"name": name, "configured_path": str(configured_path)}
        if candidate.is_file():
            resolved = candidate.resolve()
            row.update(
                {
                    "resolved_path": str(resolved),
                    "bytes": resolved.stat().st_size,
                    "sha256": sha256(resolved),
                    "clean_room_host_attested": True,
                }
            )
        else:
            raise ValueError(f"clean-room executable is not a regular file: {name}")
        rows.append(row)
    return rows


