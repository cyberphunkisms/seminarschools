#!/usr/bin/env node
'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const REPORT = 'data/audit43-browser/approved-direction-browser-audit.json';
const RELEASE_ID = '2026-07-25-site-audit43-approved-evolution-weekly-final';
const failures = [];

function read(relative) {
  try {
    return fs.readFileSync(path.join(ROOT, relative));
  } catch {
    failures.push(`${relative} is missing`);
    return Buffer.alloc(0);
  }
}

function sha256(relative) {
  return crypto.createHash('sha256').update(read(relative)).digest('hex');
}

let report = {};
try {
  report = JSON.parse(read(REPORT).toString('utf8'));
} catch (error) {
  failures.push(`${REPORT} is not valid JSON: ${error.message}`);
}
let manifest = {};
try {
  manifest = JSON.parse(read('RELEASE_MANIFEST.json').toString('utf8'));
} catch (error) {
  failures.push(`RELEASE_MANIFEST.json is not valid JSON: ${error.message}`);
}

if (report.schema !== 'seminar-schools-audit43-approved-browser-v1') {
  failures.push('browser evidence has the wrong schema');
}
if (report.release_id !== RELEASE_ID || manifest.release_id !== RELEASE_ID) {
  failures.push('browser evidence is not bound to the Audit 43 release');
}
if (report.generated_at !== manifest.generated_at) {
  failures.push('browser evidence timestamp is not release-bound');
}
if (report.source_program !== 'scripts/audit43-approved-browser.py') {
  failures.push('browser evidence names the wrong source program');
}
if (report.source_program_sha256 !== sha256('scripts/audit43-approved-browser.py')) {
  failures.push('browser evidence was not generated by the current Audit 43 program');
}
if (!/^Chromium \d+/.test(String(report.browser || ''))) {
  failures.push('browser evidence does not identify Chromium');
}
if (
  report.status !== 'passed'
  || !Array.isArray(report.checks)
  || report.checks.length < 45
  || report.checks.some(row => !row.passed)
) {
  failures.push('browser evidence is not a complete passing assertion set');
}
if (
  report.summary?.assertions !== report.checks?.length
  || report.summary?.passed !== report.checks?.length
  || report.summary?.failed !== 0
) {
  failures.push('browser evidence summary does not match its checks');
}
if (!Array.isArray(report.metrics) || report.metrics.length < 7) {
  failures.push('browser evidence lacks route geometry metrics');
} else {
  for (const row of report.metrics) {
    if (Number(row.overflow) > 1) failures.push(`${row.label} overflowed`);
    if (Number(row.cls) > 0.1) failures.push(`${row.label} exceeded CLS 0.1`);
    if (Number(row.h1) !== 1) failures.push(`${row.label} lost its visible H1`);
  }
}
const expectedScreenshots = new Set([
  'data/audit43-browser/screenshots/home-desktop.png',
  'data/audit43-browser/screenshots/home-mobile.png',
  'data/audit43-browser/screenshots/polymythcal-nearby.png',
  'data/audit43-browser/screenshots/reader-view.png',
  'data/audit43-browser/screenshots/candidate-surface.png',
  'data/audit43-browser/screenshots/teacher-first-match.png',
]);
if (
  !Array.isArray(report.screenshots)
  || report.screenshots.length !== expectedScreenshots.size
  || report.summary?.screenshots !== expectedScreenshots.size
) {
  failures.push('browser evidence does not contain exactly six screenshots');
} else {
  for (const row of report.screenshots) {
    if (!expectedScreenshots.delete(row.path)) {
      failures.push(`unexpected screenshot evidence ${row.path}`);
      continue;
    }
    const target = path.join(ROOT, row.path);
    if (!fs.existsSync(target)) {
      failures.push(`${row.path} is missing`);
    } else if (
      fs.statSync(target).size !== row.bytes
      || sha256(row.path) !== row.sha256
    ) {
      failures.push(`${row.path} does not match its evidence hash`);
    }
  }
  for (const missing of expectedScreenshots) {
    failures.push(`${missing} is absent from browser evidence`);
  }
}

if (failures.length) {
  console.error(`AUDIT 43 BROWSER EVIDENCE FAILED (${failures.length})`);
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

console.log(
  `AUDIT 43 BROWSER EVIDENCE PASSED — ${report.checks.length} assertions, `
  + `${report.metrics.length} route measurements, and six SHA-256-bound screenshots.`,
);
